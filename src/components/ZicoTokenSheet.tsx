import React, {useState, useEffect} from 'react';
import {View} from 'react-native';
import {Text, Button, Snackbar, TextInput} from 'react-native-paper';
import {observer} from 'mobx-react-lite';

import {Sheet} from '..';
import {zicoStore} from '../../store';

interface ZicoTokenSheetProps {
  isVisible: boolean;
  onDismiss: () => void;
  onSave?: () => void;
}

export const ZicoTokenSheet: React.FC<ZicoTokenSheetProps> = observer(
  ({isVisible, onDismiss, onSave}) => {
    const [token, setToken] = useState(zicoStore.token || '');
    const [showSuccess, setShowSuccess] = useState(false);
    const [secure, setSecure] = useState(true);

    useEffect(() => {
      setToken(zicoStore.token || '');
    }, [isVisible]);

    const saveToken = async () => {
      if (!token.trim()) {
        return;
      }

      await zicoStore.setToken(token.trim());
      setShowSuccess(true);
      onSave?.();
    };

    const resetToken = async () => {
      await zicoStore.clearToken();
      setToken('');
      onSave?.();
    };

    return (
      <>
        <Sheet
          isVisible={isVisible}
          onClose={onDismiss}
          title="Zico AI Memory"
          snapPoints={['60%']}>
          <Sheet.ScrollView contentContainerStyle={{padding: 20}}>
            <Text>
              Enter the token generated by your Zico memory server in Termux.
            </Text>

            <TextInput
              label="Zico Token"
              value={token}
              onChangeText={setToken}
              secureTextEntry={secure}
              autoCapitalize="none"
              autoCorrect={false}
              right={
                <TextInput.Icon
                  icon={secure ? 'eye' : 'eye-off'}
                  onPress={() => setSecure(!secure)}
                />
              }
            />

            <View style={{flexDirection: 'row', marginTop: 20}}>
              <Button
                mode="outlined"
                onPress={resetToken}
                disabled={!zicoStore.token}>
                Delete
              </Button>

              <Button
                mode="contained"
                onPress={saveToken}
                disabled={!token.trim()}
                style={{marginLeft: 10}}>
                Save
              </Button>
            </View>
          </Sheet.ScrollView>
        </Sheet>

        <Snackbar
          visible={showSuccess}
          onDismiss={() => setShowSuccess(false)}>
          Zico token saved successfully
        </Snackbar>
      </>
    );
  },
);
